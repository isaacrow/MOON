// Regenerates src/services/bibframeTerms.generated.ts from the official LC ontology files
// in ontologies/ (bibframe.rdf, bflc.rdf). Run: node scripts/build-bibframe-terms.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function readTerms(file, ns) {
  const xml = readFileSync(join(root, 'ontologies', file), 'utf8');
  const version = (xml.match(/owl:versionIRI rdf:resource="([^"]+)"/) || [])[1] || 'unknown';
  const terms = { classes: new Set(), objectProps: new Set(), datatypeProps: new Set() };
  const re = new RegExp(`<owl:(Class|ObjectProperty|DatatypeProperty|SymmetricProperty) rdf:about="${ns.replace(/[.\/]/g, '\\$&')}([A-Za-z0-9]+)"`, 'g');
  for (const [, kind, local] of xml.matchAll(re)) {
    if (kind === 'Class') terms.classes.add(local);
    else if (kind === 'DatatypeProperty') terms.datatypeProps.add(local);
    else terms.objectProps.add(local);
  }
  return { version, terms };
}

const bf = readTerms('bibframe.rdf', 'http://id.loc.gov/ontologies/bibframe/');
const bflc = readTerms('bflc.rdf', 'http://id.loc.gov/ontologies/bflc/');

const list = set => JSON.stringify([...set].sort());
const out = `// GENERATED by scripts/build-bibframe-terms.mjs from ontologies/*.rdf. Do not edit by hand.
// BIBFRAME: ${bf.version}

export const BF_CLASSES = new Set<string>(${list(bf.terms.classes)});
export const BF_OBJECT_PROPERTIES = new Set<string>(${list(bf.terms.objectProps)});
export const BF_DATATYPE_PROPERTIES = new Set<string>(${list(bf.terms.datatypeProps)});

export const BFLC_CLASSES = new Set<string>(${list(bflc.terms.classes)});
export const BFLC_OBJECT_PROPERTIES = new Set<string>(${list(bflc.terms.objectProps)});
export const BFLC_DATATYPE_PROPERTIES = new Set<string>(${list(bflc.terms.datatypeProps)});
`;

writeFileSync(join(root, 'src/services/bibframeTerms.generated.ts'), out);
console.log(`bf: ${bf.terms.classes.size} classes, ${bf.terms.objectProps.size} object, ${bf.terms.datatypeProps.size} datatype; ` +
  `bflc: ${bflc.terms.classes.size} classes, ${bflc.terms.objectProps.size} object, ${bflc.terms.datatypeProps.size} datatype`);
